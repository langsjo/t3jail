// Package sshx manages t3jail's own SSH key and ssh_config. Nothing is written
// to ~/.ssh.
package sshx

import (
	"crypto/ed25519"
	"crypto/rand"
	"encoding/pem"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"strings"

	"golang.org/x/crypto/ssh"
)

// HostAlias is the name used for the VM in the generated ssh_config.
const HostAlias = "t3jail"

// EnsureKey creates an ed25519 keypair at keyPath (+ ".pub") unless it exists,
// and returns the public key in authorized_keys format.
func EnsureKey(keyPath string) (string, error) {
	if pub, err := os.ReadFile(keyPath + ".pub"); err == nil {
		if _, err := os.Stat(keyPath); err != nil {
			return "", fmt.Errorf("%s exists but its private key is missing: %w", keyPath+".pub", err)
		}
		return strings.TrimSpace(string(pub)), nil
	} else if !errors.Is(err, fs.ErrNotExist) {
		return "", err
	}

	pub, priv, err := ed25519.GenerateKey(rand.Reader)
	if err != nil {
		return "", err
	}
	block, err := ssh.MarshalPrivateKey(priv, "t3jail")
	if err != nil {
		return "", err
	}
	sshPub, err := ssh.NewPublicKey(pub)
	if err != nil {
		return "", err
	}
	authorized := strings.TrimSpace(string(ssh.MarshalAuthorizedKey(sshPub))) + " t3jail"

	if err := os.WriteFile(keyPath, pem.EncodeToMemory(block), 0o600); err != nil {
		return "", err
	}
	if err := os.WriteFile(keyPath+".pub", []byte(authorized+"\n"), 0o644); err != nil {
		return "", err
	}
	return authorized, nil
}

// ConfigParams are the values substituted into the generated ssh_config.
type ConfigParams struct {
	User        string
	KeyPath     string
	KnownHosts  string
	ControlPath string
	// ProxyCommand is run by ssh to reach the guest; argv is shell-quoted.
	ProxyCommand []string
}

// RenderConfig returns an ssh_config for HostAlias.
func RenderConfig(p ConfigParams) string {
	quoted := make([]string, len(p.ProxyCommand))
	for i, arg := range p.ProxyCommand {
		quoted[i] = shellQuote(arg)
	}
	lines := []string{
		"# Generated by t3jail; rewritten on every use.",
		"Host " + HostAlias,
		"  HostName " + HostAlias,
		"  User " + p.User,
		"  IdentityFile " + configQuote(p.KeyPath),
		"  IdentitiesOnly yes",
		"  IdentityAgent none",
		"  ProxyCommand " + strings.Join(quoted, " "),
		"  UserKnownHostsFile " + configQuote(p.KnownHosts),
		"  StrictHostKeyChecking accept-new",
		"  ControlMaster auto",
		"  ControlPath " + configQuote(p.ControlPath),
		"  ControlPersist 60s",
		"  ForwardAgent no",
		"  ForwardX11 no",
		"  PermitLocalCommand no",
	}
	return strings.Join(lines, "\n") + "\n"
}

// shellQuote quotes s for /bin/sh, which ssh uses to run ProxyCommand.
func shellQuote(s string) string {
	if s != "" && strings.Trim(s, "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-_./=:@") == "" {
		return s
	}
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

// configQuote quotes a path for ssh_config, which splits on whitespace.
// ssh_config also expands % and ~ in these values; escape %.
func configQuote(s string) string {
	s = strings.ReplaceAll(s, "%", "%%")
	if strings.ContainsAny(s, " \t\"") {
		return `"` + strings.ReplaceAll(s, `"`, `\"`) + `"`
	}
	return s
}
